function reply(q) {
  if (!FASH.test(q)) return 'Я стилист и работаю только с одеждой и модой. Спросите, что надеть на свидание или как сочетать изумрудный цвет.';
  if (/свидан|вечер/i.test(q)) return 'На вечер: тёмная рубашка или шёлковый топ, приталенный пиджак и один золотой акцент. Обувь — лоферы или ботильоны.';
  if (/офис|работ|делов/i.test(q)) return 'Для офиса: монохром в графите и изумруде, прямые брюки и структурный пиджак. Ремень и часы — в одном металле.';
  if (/кроссов|обув/i.test(q)) return 'Универсальная база — чёрные кожаные кроссовки на объёмной подошве: подходят и к костюму, и к карго.';
  if (/цвет|изумруд|зелен/i.test(q)) return 'Изумруд лучше всего сочетается с чёрным, кремовым и золотом. Для смелости добавьте графитовый серый.';
  if (/зим|пальт|куртк|холод/i.test(q)) return 'Зимой ставьте на многослойность: тёплая водолазка, шерстяное пальто оверсайз и кожаные перчатки.';
  return 'Хороший вопрос. Уточните повод, погоду и любимые цвета, и я соберу образ. Или загляните в раздел «Сгенерировать образ».';
}
